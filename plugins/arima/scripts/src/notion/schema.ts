/**
 * Every database with its reverse relation properties added and the audit property on all.
 * This is the full list `map` verifies.
 */
export function expandedSpec(): DbSpec[] {
  const byKey = new Map<DbKey, DbSpec>(
    DATABASES.map((d) => [d.key, { ...d, props: [...d.props, text(LAST_WRITTEN_BY_RUN)] }]),
  );
  for (const owner of DATABASES) {
    for (const p of owner.props) {
      if (p.type !== 'relation' || p.relation === undefined) continue;
      const target = byKey.get(p.relation.target);
      if (target === undefined)
        throw new Error(`relation target ${p.relation.target} is not a database`);
      if (target.props.some((x) => x.name === p.relation?.reverse)) {
        throw new Error(`${target.title}.${p.relation.reverse} is defined twice`);
      }
      target.props.splice(target.props.length - 1, 0, {
        name: p.relation.reverse,
        type: 'relation',
        relation: { target: owner.key, reverse: p.name },
      });
    }
  }
  return [...byKey.values()];
}

export function dbByKey(key: DbKey): DbSpec {
  const found = expandedSpec().find((d) => d.key === key);
  if (found === undefined) throw new Error(`unknown database ${key}`);
  return found;
}

