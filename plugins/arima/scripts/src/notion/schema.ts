export type PropType =
  | 'title'
  | 'rich_text'
  | 'number'
  | 'select'
  | 'date'
  | 'people'
  | 'checkbox'
  | 'url'
  | 'files'
  | 'multi_select'
  | 'formula'
  | 'rollup'
  | 'relation';

export interface PropSpec {
  name: string;
  type: PropType;
  /** select / multi_select options. */
  options?: readonly string[];
  /** formula expression (Notion formula 2.0). */
  formula?: string;
  /** rollup definition. */
  rollup?: { relation: string; property: string; fn: 'sum' | 'show_original' };
  /** relation: the target database and the name of the reverse property created on it. */
  relation?: { target: DbKey; reverse: string };
  /** No agent may write this property (spec §9.3). */
  humanOnly?: boolean;
  /** Only these values are human-only (e.g. a gate decision); other values an agent may set. */
  humanOnlyValues?: readonly string[];
}

export interface DbSpec {
  key: DbKey;
  /** Title of the database in Notion; also how `map` finds it under the root page. */
  title: string;
  props: PropSpec[];
}

